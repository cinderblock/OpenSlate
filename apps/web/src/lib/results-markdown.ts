import type { Race, SlatePayload } from "@openslate/core";
import { positionOutcome } from "./slate-summary";

/**
 * Build a Markdown summary of a slate's results comparison for pasting into
 * Slack / Notion / a blog post / a GitHub comment. Uses a GFM table.
 *
 * Pure — no DOM, no fetch. Callers decide delivery (clipboard, file, etc.).
 */
export function slateToMarkdown(payload: SlatePayload, races: (Race | undefined)[]): string {
  const issuer = payload.attribution?.of.name ?? payload.issuer.name ?? "Slate";
  const lead = payload.attribution
    ? `# Results reported for ${issuer}\n\n_Secondhand report signed by ${payload.issuer.name ?? "issuer"}. Source: ${payload.attribution.mode}, retrieved ${payload.attribution.retrieved_at.slice(0, 10)}._\n\n`
    : `# Results for ${issuer}\n\n`;

  const header =
    "| Subject | Stance | Choice | Winner | Reporting | Outcome |\n| --- | --- | --- | --- | --- | --- |";

  const rows = payload.positions
    .map((position, i) => {
      const race = races[i];
      const winner = race?.candidates.find((c) => c.winner);
      const outcome = positionOutcome(position, race);
      return `| ${md(position.subject.title)} | ${position.stance} | ${md(position.choice ?? "—")} | ${md(winner?.name ?? "—")}${
        winner?.percent !== undefined ? ` (${winner.percent.toFixed(1)}%)` : ""
      } | ${
        race?.percent_reporting !== undefined ? `${race.percent_reporting.toFixed(1)}%` : "—"
      } | ${formatOutcome(outcome)} |`;
    })
    .join("\n");

  const footer =
    "\n\n_Source: civicAPI (third-party aggregator). Generated by [OpenSlate](https://github.com/cinderblock/openslate)._\n";

  return `${lead}${header}\n${rows}${footer}`;
}

function md(text: string): string {
  // Escape characters that would break a GFM table cell: `|` splits cells,
  // `\n` ends the row.
  return text.replace(/\\/g, "\\\\").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

function formatOutcome(outcome: string): string {
  switch (outcome) {
    case "win":
      return "✅ win";
    case "loss":
      return "❌ loss";
    case "pending":
      return "⏳ pending";
    case "na":
      return "—";
    case "unresolved":
      return "❓ not matched";
    default:
      return outcome;
  }
}
