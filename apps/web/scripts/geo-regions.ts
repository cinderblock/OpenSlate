/**
 * Writes `src/lib/regions/usDistricts.gen.ts` from the states' boundary files
 * (`us-<code>.topo.json`, written by `bun run geo --state all`): how many
 * districts each state's chambers have, or what they're called where they
 * aren't numbered from 1, and which states the app has a boundary file for.
 * The registry (src/lib/regions/usStates.ts) reads it, so labels, pickers and
 * "Find your districts" know every state's districts without loading a map.
 *
 *   bun run geo:regions                 from the files in public/geo
 *   bun run geo:regions --from <dir>    from a build somewhere else
 *   bun run geo:regions --files <dir>   the folder whose files the app ships
 *                                       (default public/geo): a state has a
 *                                       `file` only when its file is there
 *   bun run geo:regions --files all     every state built has one (the files
 *                                       are served elsewhere, VITE_GEO_BASE)
 *
 * Re-run after `bun run geo --state all`, and commit the output.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compareDistrictIds } from "@openslate/core";

const here = dirname(fileURLToPath(import.meta.url));
function option(name: string): string | undefined {
  const at = process.argv.indexOf(name);
  return at >= 0 ? process.argv[at + 1] : undefined;
}
const geoDir = join(here, "..", "public", "geo");
const fromDir = option("--from") ?? geoDir;
const files = option("--files") ?? geoDir;
const outFile = join(here, "..", "src", "lib", "regions", "usDistricts.gen.ts");

type District = string | [id: string, name: string];

/** A boundary file's layers, as far as their districts' ids and names. */
interface StateFile {
  objects: Record<string, { geometries?: Array<{ id?: string; properties?: { name?: string } }> }>;
  metadata?: { vintage?: string };
}

const built = readdirSync(fromDir)
  .map((file) => ({ file, code: /^us-([a-z]{2})\.topo\.json$/.exec(file)?.[1] }))
  .filter((entry): entry is { file: string; code: string } => entry.code !== undefined);
if (built.length === 0) throw new Error(`no us-<code>.topo.json in ${fromDir}`);

let vintage = "unknown";
const index = {
  states: built.map(({ file, code }) => {
    const topology = JSON.parse(readFileSync(join(fromDir, file), "utf8")) as StateFile;
    vintage = topology.metadata?.vintage ?? vintage;
    const districts = (layer: string): District[] =>
      (topology.objects[layer]?.geometries ?? []).map((g) =>
        g.properties?.name ? [String(g.id), g.properties.name] : String(g.id),
      );
    return {
      region: `us/${code}`,
      file,
      districts: { cd: districts("cd"), sd: districts("sd"), ad: districts("ad") },
    };
  }),
};

/**
 * A chamber as the table holds it: a count when its districts are numbered 1
 * to n, else every district, by id, with its name where the id isn't it.
 */
function chamber(districts: District[]): number | District[] | undefined {
  if (districts.length === 0) return undefined;
  const ids = districts.map((d) => (typeof d === "string" ? d : d[0]));
  const numbered = ids.every((id) => /^\d+$/.test(id));
  if (numbered) {
    const numbers = ids.map(Number).sort((a, b) => a - b);
    if (numbers.every((n, i) => n === i + 1)) return numbers.length;
  }
  return [...districts]
    .sort((a, b) =>
      compareDistrictIds(typeof a === "string" ? a : a[0], typeof b === "string" ? b : b[0]),
    )
    .map((d) => {
      if (typeof d === "string") return d;
      // A name that's only the id in capitals (35A) needs no entry of its own;
      // one with its own capitals (Washington) does.
      return d[1] === d[0].toUpperCase() ? d[0] : d;
    });
}

const states: Record<string, Record<string, unknown>> = {};
for (const state of [...index.states].sort((a, b) => a.region.localeCompare(b.region))) {
  const shipped = files === "all" || existsSync(join(files, state.file));
  const entry: Record<string, unknown> = {};
  if (shipped) entry.file = state.file;
  for (const [layer, key] of [
    ["cd", "cd"],
    ["sd", "upper"],
    ["ad", "lower"],
  ] as const) {
    const value = chamber(state.districts[layer]);
    if (value !== undefined) entry[key] = value;
  }
  states[state.region] = entry;
}

const body = Object.entries(states)
  .map(([region, entry]) => `  ${JSON.stringify(region)}: ${JSON.stringify(entry)},`)
  .join("\n");
const text = `// Generated by scripts/geo-regions.ts from the states' boundary files. Don't edit:
// run \`bun run geo:regions\` after \`bun run geo --state all\`.

/** A district that isn't one of 1 to n: its id, with its name where the id isn't it. */
export type ListedDistrict = string | readonly [id: string, name: string];

/** A chamber's districts: how many, when they're numbered 1 to n, else each one. */
export type ListedChamber = number | readonly ListedDistrict[];

export interface ListedState {
  /** The state's boundary file, when the app ships one. */
  file?: string;
  cd?: ListedChamber;
  upper?: ListedChamber;
  lower?: ListedChamber;
}

/** The Census vintage the districts are from. */
export const US_DISTRICTS_VINTAGE = ${JSON.stringify(vintage)};

/** Every state's districts as the Census maps them, by region path. */
export const US_DISTRICTS: Readonly<Record<string, ListedState>> = {
${body}
};
`;
writeFileSync(outFile, text);
const withFile = Object.values(states).filter((s) => s.file).length;
console.log(
  `wrote ${outFile}: ${Object.keys(states).length} states, ${withFile} with a boundary file, ${(text.length / 1024).toFixed(1)} KB`,
);
