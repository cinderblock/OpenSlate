// Step 3 of 3 for src/lib/regions/us-ca/districtOverlaps.ts (California district overlaps for the
// ballot order). Run from apps/web, in order:
//   bun scripts/ca-district-overlaps/1-intersect.ts
//   bun scripts/ca-district-overlaps/2-classify.ts
//   bun scripts/ca-district-overlaps/3-emit.ts src/lib/regions/us-ca/districtOverlaps.ts
//   bun scripts/ca-district-overlaps/block-equivalency.ts src/lib/regions/us-ca/districtOverlaps.ts
// The last step replaces this one's congressional and BOE tables with ones from
// the official block files: the population cut-off here dropped districts a race
// is voted in through empty territory (CD 16 / AD 21). Only the county tables
// from these steps are kept.
// Work files go in the OS temp dir (openslate-district-overlaps). plans/ballot-order.md has the method.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const target = resolve(process.argv[2]!);

import { tmpdir } from "node:os";

const work = join(tmpdir(), "openslate-district-overlaps");
mkdirSync(work, { recursive: true });
process.chdir(work);
const c = JSON.parse(readFileSync("classified.json", "utf8"));
const num = (a: string, b: string) => Number(a) - Number(b);
function group(rows: any[], keep: (v: string) => boolean, numeric: boolean) {
  const out: Record<string, any[]> = {};
  for (const r of rows) {
    if (!keep(r.verdict)) continue;
    out[r.a] ??= [];
    out[r.a]?.push(numeric ? Number(r.b) : r.b);
  }
  for (const k of Object.keys(out))
    out[k]!.sort(numeric ? (x: number, y: number) => x - y : undefined);
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => num(a, b)));
}
const data = {
  cd: group(c.cdAd, (v) => v === "real", true),
  cdUnsure: group(c.cdAd, (v) => v === "real-small", true),
  boe: group(c.boeAd, (v) => v === "real", true),
  boeUnsure: group(c.boeAd, (v) => v === "real-small", true),
  sdCounties: group(c.sdCounty, (v) => v === "real" || v === "real-small", false),
  adCounties: group(c.adCounty, (v) => v === "real" || v === "real-small", false),
};
const small = (k: string) =>
  c[k]
    .filter((r: any) => r.verdict === "real-small")
    .map((r: any) => `${r.a}/${r.b}: ${r.pop}`)
    .join(", ");
const out = `/**
 * California district overlaps for the November 3, 2026 ballot order
 * (\`ballotOrder.ts\`). Generated by \`scripts/ca-district-overlaps/\`; don't edit.
 *
 * From Census TIGERweb (tigerWMS_Current: 120th Congressional Districts, the
 * Prop 50 lines; 2026 State Legislative Districts; counties) and the state's
 * Board of Equalization layer. A pair counts when the districts' shapes share
 * more than a sliver (wider than 2 m) holding at least 100 people in the 2020
 * Census blocks inside it. Where 1 to 99 people live in the overlap, the pair is
 * in \`*Unsure\`: a county may or may not print a ballot for so few voters.
 */
export interface DistrictOverlaps {
  /** Congressional district → the Assembly districts it reaches, lowest first. */
  cd: Record<string, number[]>;
  /** Assembly districts a congressional district reaches with under 100 residents. */
  cdUnsure: Record<string, number[]>;
  /** Board of Equalization district → Assembly districts, lowest first. */
  boe: Record<string, number[]>;
  boeUnsure: Record<string, number[]>;
  /** State Senate district → the counties it reaches. */
  sdCounties: Record<string, string[]>;
  /** Assembly district → the counties it reaches. */
  adCounties: Record<string, string[]>;
}

export const CA_DISTRICTS_2026: DistrictOverlaps = ${JSON.stringify(data)};
`;
writeFileSync(target, out);
console.log("cd unsure:", small("cdAd"));
console.log("boe unsure:", small("boeAd"));
console.log("sd small:", small("sdCounty"), "| ad small:", small("adCounty"));
console.log(
  "single-county SD:",
  Object.entries(data.sdCounties).filter(([, v]) => v.length === 1).length,
  "/",
  Object.keys(data.sdCounties).length,
  "AD:",
  Object.entries(data.adCounties).filter(([, v]) => v.length === 1).length,
  "/",
  Object.keys(data.adCounties).length,
);
